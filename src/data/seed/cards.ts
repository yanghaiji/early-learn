function buildObjects(categoryId: string, rows: readonly Row[]): Card[] {
  return rows.map(([slug, zh, pinyin, en, difficulty], index) => ({
    id: `${categoryId}-${slug}`,
    kind: 'object',
    categoryId,
    zh,
    pinyin,
    en,
    image: `${IMAGE_ROOT}/${categoryId}/${slug}.webp`,
    tags: [],
    difficulty,
    sortOrder: index + 1,
    source: { ...GENERATED_SOURCE },
    createdAt: SEED_TIME,
    updatedAt: SEED_TIME,
  }));
}

function buildCharacters(rows: readonly CharRow[]): Card[] {
  return rows.map(([slug, zh, pinyin, en, strokes, words, difficulty = 1], index) => ({
    id: `characters-${slug}`,
    kind: 'character',
    categoryId: 'characters',
    zh,
    pinyin,
    en,
    image: `${IMAGE_ROOT}/characters/${slug}.webp`,
    tags: [],
    difficulty,
    sortOrder: index + 1,
    strokes,
    words: [...words],
    source: { ...GENERATED_SOURCE },
    createdAt: SEED_TIME,
    updatedAt: SEED_TIME,
  }));
}

function buildPoems(rows: readonly PoemRow[]): Card[] {
  return rows.map((row, index) => ({
    id: `poems-${row.slug}`,
    kind: 'poem',
    categoryId: 'poems',
    zh: row.zh,
    pinyin: row.pinyin,
    en: row.en,
    image: `${IMAGE_ROOT}/poems/${row.slug}.webp`,
    tags: [],
    difficulty: row.difficulty,
    sortOrder: index + 1,
    author: row.author,
    dynasty: row.dynasty,
    lines: [...row.lines],
    translation: row.translation,
    source: { ...GENERATED_SOURCE },
    createdAt: SEED_TIME,
    updatedAt: SEED_TIME,
  }));
}

